"""
Writes server/db/schema.sql (MySQL / MariaDB DDL) from the logical model in build_data_model.py.
    python build_schema_sql.py

Rules applied:
  PK -> PRIMARY KEY            UK -> UNIQUE             "UQ (a, b)" notes -> composite UNIQUE
  FK / FK* / FKu -> FOREIGN KEY (agency_id and user references included)
  delete rule: RESTRICT, except owned child rows -> CASCADE
  created_at defaults to now; updated_at is set on every update
Tables are created in dependency order, so the file runs top to bottom on an empty database.
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, '..', '..', 'server', 'db', 'schema.sql'))

src = open(os.path.join(HERE, 'build_data_model.py'), encoding='utf-8').read()
src = src[:src.index('# ───────────────────────── layout')]
ns = {'__file__': os.path.join(HERE, 'build_data_model.py')}
exec(compile(src, 'schema', 'exec'), ns)
TABLES = ns['TABLES']
by = {t['name']: t for t in TABLES}

CASCADE = {
    ('application_document', 'application_id'), ('role_menu', 'role_id'), ('membership_menu', 'membership_id'),
    ('activity_report_section', 'report_id'), ('feedback_answer', 'feedback_id'), ('group_member', 'group_id'),
    ('invitation_redemption', 'invitation_id'), ('participant_profile', 'user_id'),
}

def q(x): return f'`{x}`'

def sql_type(c):
    t = c['type']
    return 'LONGTEXT' if t == 'json' else t.upper() if t in ('text', 'date', 'datetime', 'time', 'int') else t

def column(t, c):
    name, ty = c['name'], c['type']
    parts = [q(name), 'JSON' if ty == 'json' else ty]
    nullable = c['null'] and not c['pk']
    if name == 'created_at' and not nullable:
        parts.append('NOT NULL DEFAULT CURRENT_TIMESTAMP')
    elif name == 'updated_at':
        parts.append('NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP')
    else:
        parts.append('NULL' if nullable else 'NOT NULL')
    return '  ' + ' '.join(parts)

# dependency order (parents first; self and agency/user links resolved)
order, done = [], set()
def visit(name, stack=()):
    if name in done: return
    assert name not in stack, f'cycle through {name}'
    for c in by[name]['cols']:
        if c['fk'] and c['fk'] != name: visit(c['fk'], stack + (name,))
    done.add(name); order.append(name)
for t in TABLES: visit(t['name'])
# agency_id (tenant key) points at agency; make sure agency exists before every tenant table
assert order.index('agency') < min(order.index(t['name']) for t in TABLES if any(c['fkx'] for c in t['cols']))

out = [
    '-- UniFyle (TMIS) database schema. Generated by docs/data-model/build_schema_sql.py. Do not edit by hand.',
    '-- Target: MySQL 8 / MariaDB 10.6+ (InnoDB, utf8mb4).',
    'SET NAMES utf8mb4;',
    'SET FOREIGN_KEY_CHECKS = 0;',
    '',
]
for name in order:
    t = by[name]
    lines = [column(t, c) for c in t['cols']]
    pks = [c['name'] for c in t['cols'] if c['pk']]
    lines.append(f"  PRIMARY KEY ({', '.join(q(p) for p in pks)})")
    for c in t['cols']:
        if c['uk'] and not c['pk']:
            lines.append(f"  UNIQUE KEY {q('uq_' + name + '_' + c['name'])} ({q(c['name'])})")
    for i, m in enumerate(re.findall(r'UQ \(([^)]*)\)', t['note'] or '')):
        cols = [x.strip() for x in m.split(',')]
        assert all(any(c['name'] == x for c in t['cols']) for x in cols), (name, cols)
        lines.append(f"  UNIQUE KEY {q(f'uq_{name}_{i + 1}')} ({', '.join(q(x) for x in cols)})")
    for c in t['cols']:
        parent = 'agency' if c['fkx'] and not c['fk'] else c['fk']
        if not parent: continue
        rule = 'CASCADE' if (name, c['name']) in CASCADE else 'RESTRICT'
        lines.append(f"  CONSTRAINT {q('fk_' + name + '_' + c['name'])} FOREIGN KEY ({q(c['name'])}) REFERENCES {q(parent)} ({q('id')}) ON DELETE {rule}")
    out.append(f'CREATE TABLE IF NOT EXISTS {q(name)} (')
    out.append(',\n'.join(lines))
    out.append(') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;')
    out.append('')
out.append('SET FOREIGN_KEY_CHECKS = 1;')

os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('tables', len(order), '->', OUT)
