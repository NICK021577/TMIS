/**
 * Frontend-only file helpers. There is no server yet, so "downloads" are generated in the browser:
 * real CSV files, a minimal valid PDF, a PNG, and a certificate page. Replace with API calls later.
 */

export function downloadFile(name, data, type = 'text/plain') {
  const blob = data instanceof Blob ? data : new Blob([data], { type });
  const url = URL.createObjectURL(blob);
  const a = Object.assign(document.createElement('a'), { href: url, download: name });
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function downloadCsv(name, rows) {
  const body = rows.map((r) => r.map((c) => `"${String(c ?? '').replace(/"/g, '""')}"`).join(',')).join('\n');
  downloadFile(name, `\uFEFF${body}`, 'text/csv;charset=utf-8');
}

/** A small, valid one-page PDF made of text lines. */
export function makePdf(title, lines = []) {
  const esc = (s) => String(s).replace(/[\\()]/g, '\\$&').replace(/[^\x20-\x7E]/g, '?');
  const parts = [`BT /F1 18 Tf 50 790 Td (${esc(title)}) Tj ET`];
  lines.slice(0, 40).forEach((l, i) => parts.push(`BT /F1 11 Tf 50 ${758 - i * 16} Td (${esc(l)}) Tj ET`));
  const stream = parts.join('\n');
  const objs = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
    `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];
  let pdf = '%PDF-1.4\n';
  const offsets = [];
  objs.forEach((o, i) => { offsets.push(pdf.length); pdf += `${i + 1} 0 obj\n${o}\nendobj\n`; });
  const xref = pdf.length;
  pdf += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n${offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('')}`;
  pdf += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  return new Blob([pdf], { type: 'application/pdf' });
}

function makeImage(label) {
  return new Promise((resolve) => {
    const c = Object.assign(document.createElement('canvas'), { width: 960, height: 600 });
    const g = c.getContext('2d');
    const grad = g.createLinearGradient(0, 0, 960, 600);
    grad.addColorStop(0, '#cfe4ff'); grad.addColorStop(1, '#e4d8ff');
    g.fillStyle = grad; g.fillRect(0, 0, 960, 600);
    g.fillStyle = '#1f3c80'; g.font = '600 34px Inter, sans-serif'; g.textAlign = 'center';
    g.fillText(label, 480, 290);
    g.fillStyle = '#565f78'; g.font = '400 20px Inter, sans-serif';
    g.fillText('Sample image generated by the UniFyle prototype', 480, 332);
    c.toBlob(resolve, 'image/png');
  });
}

/** Download a stand-in for a file the prototype only knows by name. */
export async function downloadPlaceholder(file, details = []) {
  const ext = file.split('.').pop().toLowerCase();
  if (ext === 'pdf') return downloadFile(file, makePdf(file.replace(/\.pdf$/i, '').replace(/_/g, ' '), ['Sample document generated by the UniFyle prototype.', '', ...details]));
  if (['png', 'jpg', 'jpeg'].includes(ext)) return downloadFile(file.replace(/\.(jpe?g)$/i, '.png'), await makeImage(file));
  if (['csv', 'xlsx'].includes(ext)) return downloadCsv(file.replace(/\.xlsx$/i, '.csv'), [['File', file], ...details.map((d) => [d])]);
  return downloadFile(file, `Sample file generated by the UniFyle prototype.\n\n${details.join('\n')}`);
}

export async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    const t = Object.assign(document.createElement('textarea'), { value: text });
    t.style.position = 'fixed'; t.style.opacity = '0';
    document.body.appendChild(t); t.select();
    let ok = false;
    try { ok = document.execCommand('copy'); } catch { ok = false; }
    t.remove();
    return ok;
  }
}

